// formatTags formats tags for JSON output
func (g *ImportGenerator) formatTags(tags map[string]string) string {
	if len(tags) == 0 {
		return "{}"
	}

	tagPairs := make([]string, 0, len(tags))
	for k, v := range tags {
		tagPairs = append(tagPairs, fmt.Sprintf(`"%s": "%s"`, k, v))
	}
	sort.Strings(tagPairs)
	
	return fmt.Sprintf(`{%s}`, strings.Join(tagPairs, ", "))
}

// generateImportScript generates a shell script to automate imports
func (g *ImportGenerator) generateImportScript(resourceGroups map[string][]aws.Resource, importFile string) error {
	content := `#!/bin/bash
# OpenTofu Import Script - AWS Transformer
# Generated by AWS Transformer
#
# This script automates the import process for discovered AWS resources.
# Features:
# - Idempotent imports (skips already imported resources)
# - Validation after each import
# - Comprehensive error handling
# - State verification
# - Terraformer-like state management
# - Backup and restore functionality

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}🚀 AWS Transformer Import Script${NC}"
echo "=================================="
echo ""

# Check if OpenTofu is installed
if ! command -v tofu &> /dev/null; then
    echo -e "${RED}❌ OpenTofu is not installed or not in PATH${NC}"
    echo "Please install OpenTofu from https://opentofu.org/"
    exit 1
fi

# Check if AWS credentials are configured
if ! aws sts get-caller-identity &> /dev/null; then
    echo -e "${YELLOW}⚠️  AWS credentials not configured or invalid${NC}"
    echo "Please configure AWS credentials using:"
    echo "  aws configure"
    echo "  or"
    echo "  export AWS_ACCESS_KEY_ID=your_key"
    echo "  export AWS_SECRET_ACCESS_KEY=your_secret"
    exit 1
fi

# Backup existing state if it exists
if [ -f "terraform.tfstate" ]; then
    echo -e "${YELLOW}📦 Backing up existing terraform.tfstate...${NC}"
    cp terraform.tfstate terraform.tfstate.backup.$(date +%Y%m%d_%H%M%S)
    echo -e "${GREEN}✅ Backup created${NC}"
fi

# Initialize OpenTofu if not already done
if [ ! -d ".terraform" ]; then
    echo -e "${BLUE}🔧 Initializing OpenTofu...${NC}"
    tofu init
    echo -e "${GREEN}✅ OpenTofu initialized${NC}"
fi

# Function to check if resource is already imported
check_resource_imported() {
    local resource_type=$1
    local resource_name=$2
    
    if tofu state list | grep -q "${resource_type}.${resource_name}"; then
        echo -e "${GREEN}✓ Resource ${resource_type}.${resource_name} already imported${NC}"
        return 0
    else
        return 1
    fi
}

# Function to import resource with validation
import_resource() {
    local import_cmd=$1
    local resource_name=$2
    local resource_type=$3
    
    echo -e "${BLUE}→ Running: $import_cmd${NC}"
    if eval "$import_cmd"; then
        echo -e "${GREEN}✓ Successfully imported $resource_name${NC}"
        
        # Validate the import with a plan
        echo -e "${BLUE}  Validating import...${NC}"
        if tofu plan -detailed-exitcode > /dev/null 2>&1; then
            echo -e "${GREEN}  ✓ Import validation successful - no changes detected${NC}"
        else
            echo -e "${YELLOW}  ⚠ Import validation failed - resource may need configuration adjustment${NC}"
        fi
    else
        echo -e "${RED}✗ Failed to import $resource_name${NC}"
        return 1
    fi
}

# Function to restore state from backup
restore_state() {
    echo -e "${YELLOW}🔄 Restoring state from backup...${NC}"
    if [ -f "terraform.tfstate.backup.$(date +%Y%m%d_%H%M%S)" ]; then
        cp terraform.tfstate.backup.$(date +%Y%m%d_%H%M%S) terraform.tfstate
        echo -e "${GREEN}✅ State restored from backup${NC}"
    else
        echo -e "${RED}❌ No backup found to restore${NC}"
    fi
}

# Import resources with idempotency checks
echo -e "${BLUE}📥 Importing resources with idempotency checks...${NC}"
echo "============================================="

# Track import results
imported_count=0
skipped_count=0
failed_count=0

`

	resourceTypes := make([]string, 0, len(resourceGroups))
	for resourceType := range resourceGroups {
		resourceTypes = append(resourceTypes, resourceType)
	}
	sort.Strings(resourceTypes)

	for _, resourceType := range resourceTypes {
		resources := resourceGroups[resourceType]
		if len(resources) > 0 {
			content += fmt.Sprintf(`# Import %s resources
echo -e "${BLUE}📦 Importing %s resources...${NC}"
`, strings.ToUpper(resourceType), strings.ToUpper(resourceType))

			for i, resource := range resources {
				resourceName := g.generateResourceName(resource, i)
				importCmd := g.generateImportCommand(resource, resourceName)
				
				// Extract the resource type from the import command
				resourceTypeFromCmd := strings.Split(strings.Split(importCmd, " ")[1], ".")[0]
				
				content += fmt.Sprintf(`# Check if %s is already imported
if check_resource_imported "%s" "%s"; then
    echo -e "${YELLOW}  Skipping %s (already imported)${NC}"
    ((skipped_count++))
else
    if import_resource "%s" "%s" "%s"; then
        ((imported_count++))
    else
        ((failed_count++))
    fi
fi

`, resource.GetName(), resourceTypeFromCmd, resourceName, resource.GetName(), importCmd, resourceName, resourceTypeFromCmd)
			}
		}
	}

	content += `# Final validation and summary
echo ""
echo -e "${BLUE}=================================="
echo "Final validation and state verification"
echo "==================================${NC}"

# Show imported resources
echo -e "${BLUE}📋 Imported resources in state:${NC}"
tofu state list

# Final plan to ensure no changes
echo ""
echo -e "${BLUE}🔍 Running final plan to ensure idempotency...${NC}"
if tofu plan -detailed-exitcode > /dev/null 2>&1; then
    echo -e "${GREEN}✅ SUCCESS: All resources imported successfully!${NC}"
    echo -e "${GREEN}✅ No changes detected - infrastructure is in sync with state${NC}"
    echo ""
    echo -e "${GREEN}🎉 Your AWS infrastructure is now managed by OpenTofu!${NC}"
    echo -e "${GREEN}You can now run 'tofu apply' safely - it will show 'no changes'${NC}"
else
    echo -e "${YELLOW}⚠ WARNING: Some resources may need configuration adjustment${NC}"
    echo -e "${YELLOW}Run 'tofu plan' to see what needs to be fixed${NC}"
fi

# Print summary
echo ""
echo -e "${BLUE}📊 Import Summary:${NC}"
echo -e "  ${GREEN}✓ Successfully imported: $imported_count${NC}"
echo -e "  ${YELLOW}⏭ Skipped (already imported): $skipped_count${NC}"
echo -e "  ${RED}✗ Failed: $failed_count${NC}"

if [ $failed_count -gt 0 ]; then
    echo ""
    echo -e "${YELLOW}⚠ Some imports failed. You may need to:${NC}"
    echo -e "  1. Check AWS permissions"
    echo -e "  2. Verify resource IDs are correct"
    echo -e "  3. Manually configure resource definitions"
    echo -e "  4. Run 'tofu plan' to see specific issues"
fi

echo ""
echo -e "${BLUE}🚀 Next steps:${NC}"
echo -e "  1. Review the plan output above"
echo -e "  2. Customize resource configurations if needed"
echo -e "  3. Run 'tofu apply' to ensure everything is in sync"
echo -e "  4. Commit your OpenTofu files to version control"
echo ""
echo -e "${BLUE}💡 Tips:${NC}"
echo -e "  • Use 'tofu state show <resource>' to inspect imported resources"
echo -e "  • Use 'tofu plan' to verify no changes are needed"
echo -e "  • Use 'tofu apply' to finalize the import process"
echo -e "  • Backup your state file: cp terraform.tfstate terraform.tfstate.backup"
echo ""
echo -e "${GREEN}✅ Import process completed!${NC}"
`

	return g.writeFile(filepath.Join(g.outputDir, "import.sh"), content)
}

