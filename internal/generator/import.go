// ImportGenerator represents an OpenTofu import statement generator
type ImportGenerator struct {
	outputDir string
	verbose   bool
}

// NewImportGenerator creates a new import generator instance
func NewImportGenerator(outputDir string, verbose bool) *ImportGenerator {
	return &ImportGenerator{
		outputDir: outputDir,
		verbose:   verbose,
	}
}

// GenerateImportStatements creates OpenTofu import statements from AWS resources
func (g *ImportGenerator) GenerateImportStatements(resources []aws.Resource, region, importFile, stateFile string) error {
	// Create output directory
	if err := os.MkdirAll(g.outputDir, 0755); err != nil {
		return fmt.Errorf("failed to create output directory: %w", err)
	}

	// Group resources by type
	resourceGroups := g.groupResourcesByType(resources)

	// Generate import statements file
	if err := g.generateImportFile(resourceGroups, region, importFile); err != nil {
		return fmt.Errorf("failed to generate import file: %w", err)
	}

	// Generate state file template if requested
	if stateFile != "" {
		if err := g.generateStateTemplate(resourceGroups, region, stateFile); err != nil {
			return fmt.Errorf("failed to generate state template: %w", err)
		}
	}

	// Generate import script
	if err := g.generateImportScript(resourceGroups, importFile); err != nil {
		return fmt.Errorf("failed to generate import script: %w", err)
	}

	// Generate README for import process
	if err := g.generateImportREADME(resources, region, importFile, stateFile); err != nil {
		return fmt.Errorf("failed to generate import README: %w", err)
	}

	return nil
}

// groupResourcesByType groups resources by their type
func (g *ImportGenerator) groupResourcesByType(resources []aws.Resource) map[string][]aws.Resource {
	groups := make(map[string][]aws.Resource)
	for _, resource := range resources {
		resourceType := resource.GetType()
		groups[resourceType] = append(groups[resourceType], resource)
	}
	return groups
}

// generateImportFile generates the main import statements file
func (g *ImportGenerator) generateImportFile(resourceGroups map[string][]aws.Resource, region, importFile string) error {
	content := fmt.Sprintf(`# OpenTofu Import Statements
# Generated by AWS Transformer
# Region: %s
# 
# This file contains import statements for existing AWS resources.
# Run these commands to import resources into your OpenTofu state.
#
# Usage:
# 1. Ensure you have the corresponding resource definitions in your .tf files
# 2. Run each import command individually
# 3. Verify the import with 'tofu plan'
#
# Example:
# tofu import aws_vpc.my_vpc vpc-12345678

`, region)

	// Add provider configuration
	content += fmt.Sprintf(`# Provider configuration
provider "aws" {
  region = "%s"
}

`, region)

	// Add resource definitions and import statements
	resourceTypes := make([]string, 0, len(resourceGroups))
	for resourceType := range resourceGroups {
		resourceTypes = append(resourceTypes, resourceType)
	}
	sort.Strings(resourceTypes)

	for _, resourceType := range resourceTypes {
		resources := resourceGroups[resourceType]
		if len(resources) > 0 {
			content += fmt.Sprintf(`# %s Resources
`, strings.ToUpper(resourceType))

			// Add resource definitions
			for i, resource := range resources {
				resourceName := g.generateResourceName(resource, i)
				content += g.generateResourceDefinition(resource, resourceName)
			}

			content += "\n"
		}
	}

	// Add import statements section
	content += `# Import Statements
# Run these commands to import existing resources into OpenTofu state
#
# Note: Make sure you have the corresponding resource definitions above
# before running the import commands.

`

	for _, resourceType := range resourceTypes {
		resources := resourceGroups[resourceType]
		if len(resources) > 0 {
			content += fmt.Sprintf(`# %s Import Commands
`, strings.ToUpper(resourceType))

			for i, resource := range resources {
				resourceName := g.generateResourceName(resource, i)
				importCmd := g.generateImportCommand(resource, resourceName)
				content += fmt.Sprintf(`# %s
%s

`, resource.GetName(), importCmd)
			}
		}
	}

	return g.writeFile(filepath.Join(g.outputDir, importFile), content)
}

// generateResourceName generates a unique resource name for OpenTofu
func (g *ImportGenerator) generateResourceName(resource aws.Resource, index int) string {
	baseName := aws.SanitizeResourceName(resource.GetName())
	if index > 0 {
		return fmt.Sprintf("%s_%d", baseName, index)
	}
	return baseName
}

